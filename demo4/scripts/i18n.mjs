const exactZh = new Map(zhPairs);
const replacementPairs = [...zhPairs]
  .filter(([source]) => /[A-Za-z]/.test(source))
  .sort(([left], [right]) => right.length - left.length);

function replaceWholePhrase(value, source, target) {
  const escaped = source.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const startsWithWord = /^[A-Za-z0-9]/.test(source);
  const endsWithWord = /[A-Za-z0-9]$/.test(source);
  const prefix = startsWithWord ? '(^|[^A-Za-z0-9])' : '()';
  const suffix = endsWithWord ? '(?=$|[^A-Za-z0-9])' : '';
  return value.replace(new RegExp(`${prefix}${escaped}${suffix}`, 'g'), (_, boundary) => `${boundary}${target}`);
}

function translateDynamic(value) {
  let match = value.match(/^(\d+) illustrative records$/);
  if (match) return `${match[1]} 条示例记录`;
  match = value.match(/^(\d+) open$/);
  if (match) return `${match[1]} 项待处理`;
  match = value.match(/^No (.+) yet$/i);
  if (match) return `暂无${translateText(match[1], CHINESE_LANGUAGE)}`;
  match = value.match(/^Continue to (.+)$/);
  if (match) return `继续：${translateText(match[1], CHINESE_LANGUAGE)}`;
  match = value.match(/^(.+) is included as illustrative data for this display demo\.$/);
  if (match) return `${translateText(match[1], CHINESE_LANGUAGE)}已作为本展示 Demo 的示例数据。`;
  match = value.match(/^(.+) is the strongest current signal\.$/);
  if (match) return `${translateText(match[1], CHINESE_LANGUAGE)}是当前最强信号。`;
  match = value.match(/^(.+) is shaping the next operational decision\.$/);
  if (match) return `${translateText(match[1], CHINESE_LANGUAGE)}正在影响下一项运营决策。`;
  match = value.match(/^(.+) against the previous period\.$/);
  if (match) return `${translateText(match[1], CHINESE_LANGUAGE)}，较上一周期。`;
  match = value.match(/^(.+) vs previous period$/);
  if (match) return `${translateText(match[1], CHINESE_LANGUAGE)}，较上一周期`;
  match = value.match(/^(.+) growth trajectory$/);
  if (match) return `${translateText(match[1], CHINESE_LANGUAGE)}增长趋势`;
  match = value.match(/^(.+) trajectory$/);
  if (match) return `${translateText(match[1], CHINESE_LANGUAGE)}趋势`;
  match = value.match(/^(.+) details$/);
  if (match) return `${translateText(match[1], CHINESE_LANGUAGE)}详情`;
  match = value.match(/^(.+) working view opened$/);
  if (match) return `已打开${translateText(match[1], CHINESE_LANGUAGE)}工作视图`;
  match = value.match(/^(.+) export prepared$/);
  if (match) return `${translateText(match[1], CHINESE_LANGUAGE)}导出文件已准备`;
  match = value.match(/^(.+) flow opened$/);
  if (match) return `已打开${translateText(match[1], CHINESE_LANGUAGE)}流程`;
  return null;
}

export function normalizeLanguage(language) {
  return language === CHINESE_LANGUAGE ? CHINESE_LANGUAGE : DEFAULT_LANGUAGE;
}

export function translateText(value = '', language = DEFAULT_LANGUAGE) {
  const source = String(value);
  if (normalizeLanguage(language) !== CHINESE_LANGUAGE || !source.trim()) return source;

  const leading = source.match(/^\s*/)?.[0] ?? '';
  const trailing = source.match(/\s*$/)?.[0] ?? '';
  const core = source.slice(leading.length, source.length - trailing.length || undefined);
  const exact = exactZh.get(core);
  if (exact) return `${leading}${exact}${trailing}`;

  const dynamic = translateDynamic(core);
  if (dynamic) return `${leading}${dynamic}${trailing}`;

  const translated = replacementPairs.reduce(
    (result, [from, to]) => replaceWholePhrase(result, from, to),
    core,
  );
  return `${leading}${translated}${trailing}`;
}

export function localizeHtml(html, language = DEFAULT_LANGUAGE) {
  if (normalizeLanguage(language) !== CHINESE_LANGUAGE) return html;

  const localizedText = html.replace(/>([^<>]+)</g, (match, text) => `>${translateText(text, language)}<`);
  return localizedText.replace(
    /\b(aria-label|placeholder|title|data-toast)="([^"]*)"/g,
    (match, attribute, value) => `${attribute}="${translateText(value, language)}"`,
  );
}
